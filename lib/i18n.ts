const dictionaries: Record<Lang, Record<TranslationKey, string>> = {
  en: en as unknown as Record<TranslationKey, string>,
  kh,
};

export function t(
  lang: Lang,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  let text = dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function isLang(value: string | undefined): value is Lang {
  return value === "en" || value === "kh";
}

export function translateBoth(key: TranslationKey): { en: string; kh: string } {
  return { en: t("en", key), kh: t("kh", key) };
}
